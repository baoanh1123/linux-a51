/* Bias control value, indexed by escape clock in MHz minus 7 (7..20 MHz) */
static const u32 exynos9610_dsim_b_dphyctl[] = {
	0x0af, 0x0c8, 0x0e1, 0x0fa,			/* esc 7 ~ 10 */
	0x113, 0x12c, 0x145, 0x15e, 0x177,	/* esc 11 ~ 15 */
	0x190, 0x1a9, 0x1c2, 0x1db, 0x1f4,	/* esc 16 ~ 20 */
};

/*
 * The vendor PMS calculation tool searches a small divider with a multiplier up
 * to 300 and keeps the VCO inside 1.5..3 GHz.  Staying in that space
 * reproduces the hardware-verified values.
 */
#define EXYNOS9610_DSIM_PLL_MAX_P	6
#define EXYNOS9610_DSIM_PLL_MAX_M	300
#define EXYNOS9610_DSIM_PLL_VCO_MIN_KHZ	1500000
#define EXYNOS9610_DSIM_PLL_VCO_MAX_KHZ	3000000

#define EXYNOS9610_DSIM_ESC_CLK_MIN_MHZ	7
#define EXYNOS9610_DSIM_ESC_CLK_MAX_MHZ	20

/**
 * exynos9610_dsim_esc_div() - escape clock divider
 * @hs_clk_mhz: HS clock in MHz
 * @esc_clk_mhz: requested escape clock in MHz
 *
 * The escape clock is derived from the byte clock (HS clock / 16) so that it
 * does not exceed the requested rate.  Returns the divider to program.
 */
u32 exynos9610_dsim_esc_div(u32 hs_clk_mhz, u32 esc_clk_mhz)
{
	u32 word_clk = hs_clk_mhz / 16;
	u32 div = word_clk / esc_clk_mhz;

	if (!div)
		return 1;

	if (word_clk / div > esc_clk_mhz)
		div++;

	return div;
}

/**
 * exynos9610_dsim_dphy_timing() - look up D-PHY timings for a HS clock
 * @hs_clk_mhz: HS clock in MHz
 * @esc_clk_mhz: escape clock in MHz, as programmed by the divider
 * @timing: filled with the timing values
 */
int exynos9610_dsim_dphy_timing(u32 hs_clk_mhz, u32 esc_clk_mhz,
				struct exynos9610_dsim_dphy_timing *timing)
{
	const u32 (*row)[10];
	u32 top = exynos9610_dsim_dphy_timing_table[0][0];
	u32 count = ARRAY_SIZE(exynos9610_dsim_dphy_timing_table);
	u32 index;

	if (hs_clk_mhz > top || top - hs_clk_mhz > (count - 1) * 10)
		return -EINVAL;

	index = (top - hs_clk_mhz) / 10;
	row = &exynos9610_dsim_dphy_timing_table[index];

	if (esc_clk_mhz < EXYNOS9610_DSIM_ESC_CLK_MIN_MHZ ||
	    esc_clk_mhz > EXYNOS9610_DSIM_ESC_CLK_MAX_MHZ)
		return -EINVAL;

	timing->bps = (*row)[0];
	timing->clk_prepare = (*row)[1];
	timing->clk_zero = (*row)[2];
	timing->clk_post = (*row)[3];
	timing->clk_trail = (*row)[4];
	timing->hs_prepare = (*row)[5];
	timing->hs_zero = (*row)[6];
	timing->hs_trail = (*row)[7];
	timing->lpx = (*row)[8];
	timing->hs_exit = (*row)[9];
	timing->b_dphyctl =
		exynos9610_dsim_b_dphyctl[esc_clk_mhz - EXYNOS9610_DSIM_ESC_CLK_MIN_MHZ];

	return 0;
}

/**
 * exynos9610_dsim_pll_params() - find P/M/S for a HS clock
 * @target_khz: wanted HS clock in kHz
 * @ref_khz: PLL reference clock in kHz
 * @pll: filled with the best divider/multiplier/shift found
 *
 * The PLL runs at m * ref / (p * 2^s), so a coarse search over the small
 * divider and shift spaces with the multiplier solved directly is enough to
 * find an exact or near-exact match.
 *
 * The search space is the vendor PMS tool's: a small divider, a multiplier up
 * to 300 and a VCO inside the 1.5..3 GHz band.  Without those limits the search
 * finds equally exact but unusable combinations (p=13 m=600 for 1200 MHz), and
 * with them it reproduces the vendor's values exactly - 1200 MHz gives
 * p=3 m=277 s=1, i.e. PLLCTRL 0x68a9, which is what the boot loader programs.
 */
int exynos9610_dsim_pll_params(u32 target_khz, u32 ref_khz,
			       struct exynos9610_dsim_pll *pll)
{
	u32 best_err = U32_MAX, best_m = U32_MAX;
	u32 p, s;

	if (!ref_khz || !target_khz)
		return -EINVAL;

	for (s = 0; s < 4; s++) {
		for (p = 1; p <= EXYNOS9610_DSIM_PLL_MAX_P; p++) {
			u64 scaled = (u64)target_khz * p << s;
			u32 m = DIV_ROUND_CLOSEST_ULL(scaled, ref_khz);
			u32 vco, freq, err;

			if (!m || m > EXYNOS9610_DSIM_PLL_MAX_M)
				continue;

			vco = div_u64((u64)m * ref_khz, p);
			if (vco < EXYNOS9610_DSIM_PLL_VCO_MIN_KHZ ||
			    vco > EXYNOS9610_DSIM_PLL_VCO_MAX_KHZ)
				continue;

			freq = vco >> s;
			err = abs_diff(freq, target_khz);

			if (err > best_err || (err == best_err && m >= best_m))
				continue;

			best_err = err;
			best_m = m;
			pll->p = p;
			pll->m = m;
			pll->s = s;
			pll->freq_khz = freq;
		}
	}

	return best_err == U32_MAX ? -EINVAL : 0;
}

